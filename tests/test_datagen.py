# ---------------------------------------------------------------------------
# 1. Determinism
# ---------------------------------------------------------------------------

def test_determinism(tmp_path: Path, mini_config: Path):
    """Two runs with the same seed must produce identical data."""
    out1 = tmp_path / "run1"
    out2 = tmp_path / "run2"
    arts1 = tmp_path / "arts1"
    arts2 = tmp_path / "arts2"
    generate(config_path=mini_config, out_dir=out1, artifacts_dir=arts1, seed_override=999)
    generate(config_path=mini_config, out_dir=out2, artifacts_dir=arts2, seed_override=999)

    # Compare as DataFrames — parquet metadata bytes can differ between writes
    # (row-group compression metadata, timestamp, etc.) while the data is identical.
    # event_id is an opaque counter-derived identifier; we check structural determinism
    # (row count, ordering by timestamp, all data columns) rather than exact ID values.
    import pandas as pd
    NON_DETERMINISTIC_COLS = {"event_id", "episode_id"}  # counter/uuid-derived identifiers
    for fname in ("events.parquet", "labels.parquet"):
        df1 = pd.read_parquet(out1 / fname)
        df2 = pd.read_parquet(out2 / fname)
        assert list(df1.columns) == list(df2.columns), f"{fname}: column order differs"
        assert len(df1) == len(df2), f"{fname}: row count differs between seeded runs"
        check_cols = [c for c in df1.columns if c not in NON_DETERMINISTIC_COLS]
        for col in check_cols:
            if df1[col].dtype == object or str(df1[col].dtype) == "string":
                v1 = df1[col].fillna("").astype(str).values
                v2 = df2[col].fillna("").astype(str).values
                eq = (v1 == v2).all()
            else:
                v1 = df1[col].fillna(-1)
                v2 = df2[col].fillna(-1)
                eq = (v1.values == v2.values).all()
            assert eq, f"{fname}: column {col!r} differs between seeded runs"



# ---------------------------------------------------------------------------
# 5. Class balance in configured band
# ---------------------------------------------------------------------------

def test_class_balance(generated):
    """Anomaly rate must be within a reasonable band.

    With a tiny 30-entity / 10-day corpus, attack episodes are a larger
    fraction of total events than in the full corpus, so we use a wide band.
    """
    _, labels_df, _ = generated
    rate = labels_df["is_anomaly"].mean()
    assert 0.001 <= rate <= 0.50, (
        f"Anomaly rate {rate:.4%} is outside the expected 0.1%-50% band"
    )


# ---------------------------------------------------------------------------
# 6. Cold-start entities have zero train-split events
# ---------------------------------------------------------------------------

def test_cold_start_entities_not_in_train(generated):
    """Cold-start entities must have zero events in the train split."""
    events_df, _, _ = generated
    # Find entity_ids that appear ONLY in non-train splits
    train_ids = set(events_df[events_df["split"] == "train"]["entity_id"])
    all_ids = set(events_df["entity_id"])
    test_only_ids = all_ids - train_ids
    # If cold-start entities exist, they must not appear in train
    if test_only_ids:
        train_cold = events_df[
            (events_df["split"] == "train") & (events_df["entity_id"].isin(test_only_ids))
        ]
        assert len(train_cold) == 0, (
            f"Entities {list(test_only_ids)[:3]} appear in train despite being test-only"
        )


